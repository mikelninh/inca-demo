import {test,expect} from '@playwright/test'

test('v5: a verified quote is highlighted in the actual rendered PDF, and tampering removes the anchor',async({page})=>{
 const external:string[]=[]
 const origin=new URL(test.info().project.use.baseURL??'http://127.0.0.1:4173').origin
 page.on('request',r=>{if(!r.url().startsWith(origin+'/'))external.push(r.url())})
 await page.goto('/inca-demo/?lab=1')
 await expect(page.getByRole('heading',{name:/See the evidence/})).toBeVisible()
 await expect(page.locator('.doclab-file')).toHaveCount(3,{timeout:30000})
 await expect.poll(async()=>page.locator('.doclab-pdf-canvas').evaluate((e:HTMLCanvasElement)=>e.width),{timeout:30000}).toBeGreaterThan(200)
 await expect(page.locator('.doclab-page-anchor').first()).toBeVisible()
 await page.getByRole('button',{name:/Deckungsgrenze/}).last().click()
 await expect(page.locator('.doclab-reader-toolbar')).toContainText('2 / 2')
 await expect(page.locator('.doclab-page-source mark')).toContainText(/Vorschaden/)
 await expect(page.locator('.doclab-page-anchor').first()).toBeVisible()
 await page.getByRole('button',{name:'Zitat manipulieren'}).click()
 await expect(page.locator('.doclab-status')).toContainText('Fundstelle ungültig')
 await expect(page.locator('.doclab-page-anchor')).toHaveCount(0)
 await page.getByRole('button',{name:'Normal'}).click()
 await expect(page.locator('.doclab-status')).toContainText('Widerspruch')
 expect(external).toEqual([])
})

test('v5 mobile: source/befund/akte tabs, document zoom and citation-to-original navigation',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/inca-demo/?lab=1')
 await expect(page.locator('.doclab-file')).toHaveCount(3,{timeout:30000})
 await expect(page.getByRole('tab',{name:/Quelle/})).toHaveAttribute('aria-selected','true')
 await expect(page.locator('.doclab-pdf-canvas')).toBeVisible()
 await page.getByRole('button',{name:'PDF vergrößern'}).click()
 await expect(page.locator('.doclab-zoom output')).toHaveText('125%')
 await page.getByRole('tab',{name:/Akte/}).click()
 await expect(page.locator('.doclab-file').first()).toBeVisible()
 await page.getByRole('button',{name:/Deckungsgrenze/}).last().click()
 await expect(page.getByRole('tab',{name:/Quelle/})).toHaveAttribute('aria-selected','true')
 await expect(page.locator('.doclab-reader-toolbar')).toContainText('2 / 2')
 await expect(page.locator('.doclab-page-anchor').first()).toBeVisible()
 await page.getByRole('button',{name:/Befund & nächste Aktion/}).click()
 await expect(page.getByRole('tab',{name:/Befund/})).toHaveAttribute('aria-selected','true')
 await expect(page.locator('.doclab-status')).toBeVisible()
 await page.getByRole('button',{name:'Rechnung entfernen'}).click()
 await expect(page.locator('.doclab-status')).toContainText('Fehlende Unterlagen')
 const excess=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth)
 expect(excess).toBeLessThanOrEqual(1)
})
