import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'

test('operator desk: triage three real PDF dossiers, handle exceptions and export privacy-safe audit',async({page})=>{
 const origin=new URL(test.info().project.use.baseURL??'http://127.0.0.1:4173').origin
 const external:string[]=[], writes:string[]=[]
 page.on('request',r=>{
  if(!r.url().startsWith(origin+'/'))external.push(r.url())
  if(['POST','PATCH','PUT','DELETE'].includes(r.method()))writes.push(r.url())
 })
 await page.goto('/inca-demo/')
 await expect(page.getByRole('heading',{name:/Cases in/})).toBeVisible()
 await expect(page.locator('.desk-case')).toHaveCount(3,{timeout:30000})
 await expect(page.locator('.desk-source')).toContainText('Original & Belege')
 await expect(page.locator('.desk-decision-card')).toContainText('Widerspruch')
 // Priorities: the missing-invoice dossier is first, regardless of demo order.
 await expect(page.locator('.desk-case').first()).toContainText('HR-C09')
 await page.locator('.desk-case').filter({hasText:'Einbruch'}).click()
 await expect(page.locator('.desk-decision-card')).toContainText('Fehlende Primärunterlagen')
 await expect(page.getByRole('button',{name:/Zur Fachprüfung/})).toHaveCount(0)
 await page.getByRole('textbox',{name:/OPERATOREN-NOTIZ/}).fill('CUSTOMER PRIVATE NAME: DO NOT EXPORT')
 await page.getByRole('button',{name:/Unterlagen nachfordern/}).click()
 await expect(page.locator('.desk-metrics')).toContainText('1')
 await expect(page.locator('.desk-review-history')).toContainText('Unterlagen nachfordern')
 // A source-backed mismatch can only be sent to a human specialist.
 await page.locator('.desk-case').filter({hasText:'Parkrempler'}).click()
 await expect(page.locator('.desk-decision-card')).toContainText('Möglicher Widerspruch')
 await page.locator('.desk-citation-list button').filter({hasText:'Deckungsgrenze'}).last().click()
 await expect(page.locator('.desk-page-controls')).toContainText('2 / 2')
 await expect(page.locator('.desk-anchor-rect').first()).toBeVisible()
 await page.getByRole('button',{name:/An Spezialist:in/}).click()
 await expect(page.locator('.desk-review-history')).toContainText('An Fachprüfung übergeben')
 await page.getByRole('button',{name:/Nächsten offenen Fall/}).click()
 await expect(page.locator('.desk-decision-card')).toContainText('Prüfung vorbereiten')
 await page.getByRole('button',{name:/Zur Fachprüfung/}).click()
 await expect(page.locator('.desk-review-history')).toContainText('Zur regulären Fachprüfung')
 const dl=page.waitForEvent('download')
 await page.getByRole('button',{name:/Sitzungsbericht exportieren/}).click()
 const output=JSON.parse(await readFile(await (await dl).path() as string,'utf8'))
 expect(output.schema).toBe('claim-os-6-operator-audit-v1')
 expect(output.cases).toHaveLength(3)
 expect(output.human_review_events).toBe(3)
 expect(output.no_production_integration).toBe(true)
 expect(output.no_ai_model_calls).toBe(true)
 expect(output.no_autonomous_payments).toBe(true)
 expect(output.measured_human_time_saving).toBe(null)
 const printed=JSON.stringify(output)
 expect(printed).not.toContain('CUSTOMER PRIVATE NAME')
 expect(printed).not.toContain('Schadenmeldung_KFZ-A17')
 expect(printed).not.toContain('Heckklappe')
 expect(external).toEqual([])
 expect(writes).toEqual([])
})
test('operator desk: multi-file real PDF intake and role-based fail-closed retagging',async({page})=>{
 // Produce authentic PDF bytes using the browser-based scenario generator; do not use stub text files.
 await page.goto('/inca-demo/?lab=1')
 await expect(page.locator('.doclab-file')).toHaveCount(3,{timeout:30000})
 const files:{name:string;mimeType:string;buffer:Buffer}[]=[]
 for(const [index,role] of ['Schadenmeldung','Vertrag','Rechnung'].entries()){
  if(index>0)await page.locator('.doclab-file >button').nth(index).click()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:/PDF herunterladen/}).click()
  const saved=await download
  const buffer=await readFile(await saved.path() as string)
  expect(buffer.subarray(0,5).toString()).toBe('%PDF-')
  files.push({name:'CASE-104__'+role+'.pdf',mimeType:'application/pdf',buffer})
 }
 await page.goto('/inca-demo/')
 await expect(page.locator('.desk-case')).toHaveCount(3,{timeout:30000})
 await page.locator('input[aria-label="Mehrere PDFs importieren"]').setInputFiles(files)
 await expect(page.locator('.desk-case')).toHaveCount(4,{timeout:30000})
 await expect(page.locator('.desk-source')).toContainText('Original & Belege')
 await expect(page.locator('.desk-decision-card')).toContainText('Möglicher Widerspruch')
 await page.locator('.desk-role-editor summary').click()
 await page.getByRole('combobox',{name:'Dokumentart für CASE-104__Rechnung.pdf'}).selectOption('unknown')
 await expect(page.locator('.desk-decision-card')).toContainText('Fehlende Primärunterlagen')
 await expect(page.getByRole('button',{name:/Zur Fachprüfung/})).toHaveCount(0)
 await page.getByRole('combobox',{name:'Dokumentart für CASE-104__Rechnung.pdf'}).selectOption('invoice')
 await expect(page.locator('.desk-decision-card')).toContainText('Möglicher Widerspruch')
 // Resume an incomplete claim in place when its missing invoice arrives.
 await page.locator('.desk-case').filter({hasText:'Einbruch'}).click()
 await expect(page.locator('.desk-decision-card')).toContainText('Fehlende Primärunterlagen')
 await page.getByRole('button',{name:/Unterlagen nachfordern/}).click()
 await expect(page.locator('.desk-review-history')).toContainText('Unterlagen nachfordern')
 await page.locator('input[aria-label="Dokumente zu diesem Fall ergänzen"]').setInputFiles({
  name:'Rechnung_Nachreichung.pdf',mimeType:'application/pdf',buffer:files[2].buffer
 })
 await expect(page.locator('.desk-document-strip button')).toHaveCount(3,{timeout:30000})
 await expect(page.locator('.desk-decision-card')).toContainText('Fehlende Angabe im Einbruchfall')
 await expect(page.locator('.desk-review-history')).toContainText('Wieder geöffnet')
})
