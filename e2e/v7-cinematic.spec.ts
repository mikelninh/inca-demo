import {test,expect} from '@playwright/test'
import {mkdir,readFile} from 'node:fs/promises'

test('cinematic scenes: initial story, source-verified reveal, safe human handoff and privacy-clean audit',async({page})=>{
 const base=new URL(test.info().project.use.baseURL??'http://127.0.0.1:4173').origin
 const cross:string[]=[],writes:string[]=[]
 page.on('request',r=>{
  if(!r.url().startsWith(base+'/'))cross.push(r.url())
  if(['POST','PUT','PATCH','DELETE'].includes(r.method()))writes.push(r.url())
 })
 await page.setViewportSize({width:1440,height:900})
 await page.goto('/inca-demo/')
 await expect(page.getByRole('heading',{name:/Something doesn't add up/})).toBeVisible({timeout:30000})
 await expect(page.locator('.cine-document-tabs button')).toHaveCount(3)
 await expect.poll(async()=>page.locator('.cine-paper canvas').evaluate((c:HTMLCanvasElement)=>c.width),{timeout:30000}).toBeGreaterThan(100)
 await expect(page.getByRole('tab',{name:/Der Fall/})).toHaveAttribute('aria-selected','true')
 await mkdir('test-results/v7',{recursive:true})
 await page.screenshot({path:'test-results/v7/01-the-case.png',animations:'disabled'})
 await page.getByRole('button',{name:/Beleg entdecken/}).click()
 await expect(page.getByRole('tab',{name:/Die Fundstelle/})).toHaveAttribute('aria-selected','true')
 await expect(page.locator('.cine-evidence-list button').first()).toBeVisible()
 await expect(page.locator('.cine-quote')).toContainText('WORTGLEICH IM ORIGINAL')
 await expect(page.locator('.cine-page-controls')).toContainText('2')
 await expect(page.locator('.cine-source-highlight').first()).toBeVisible({timeout:10000})
 await page.screenshot({path:'test-results/v7/02-the-evidence.png',animations:'disabled'})
 await page.getByRole('button',{name:/Nächste Handlung/}).click()
 await expect(page.getByRole('heading',{name:'The decision stays human.'})).toBeVisible()
 await expect(page.getByRole('button',{name:/An Spezialist:in/})).toBeVisible()
 await page.screenshot({path:'test-results/v7/03-the-action.png',animations:'disabled'})
 await page.getByRole('textbox',{name:/OPERATOR-NOTIZ/}).fill('IDENTITY SECRET MUST NOT LEAK')
 await page.getByRole('button',{name:/An Spezialist:in/}).click()
 await expect(page.locator('.cine-completed')).toContainText('Schritt dokumentiert.')
 const dl=page.waitForEvent('download')
 await page.getByRole('button',{name:/Sitzungsbericht ohne Rohdaten/}).click()
 const file=await dl
 const audit=JSON.parse(await readFile(await file.path() as string,'utf8'))
 expect(audit.schema).toBe('claim-os-6-operator-audit-v1')
 expect(audit.human_review_events).toBe(1)
 expect(audit.no_ai_model_calls).toBe(true)
 expect(audit.no_autonomous_payments).toBe(true)
 expect(audit.measured_human_time_saving).toBe(null)
 const str=JSON.stringify(audit)
 expect(str).not.toContain('IDENTITY SECRET')
 expect(str).not.toContain('Werkstattrechnung')
 expect(str).not.toContain('Vorschaden')
 expect(cross).toEqual([])
 expect(writes).toEqual([])
})
