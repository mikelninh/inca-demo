test('cinematic imports genuine multi-document PDF and reclassifies file type fail-closed',async({page})=>{
 await page.goto('/inca-demo/?lab=1')
 await expect(page.locator('.doclab-file')).toHaveCount(3,{timeout:30000})
 const files:{name:string;mimeType:string;buffer:Buffer}[]=[]
 for(let i=0;i<3;i++){
  if(i>0)await page.locator('.doclab-file >button').nth(i).click()
  const d=page.waitForEvent('download')
  await page.getByRole('button',{name:/PDF herunterladen/}).click()
  const buffer=await readFile(await (await d).path() as string)
  files.push({name:'CASE-123__'+['Schadenmeldung','Vertrag','Rechnung'][i]+'.pdf',mimeType:'application/pdf',buffer})
 }
 await page.goto('/inca-demo/')
 await expect(page.getByRole('heading',{name:/Something doesn't add up/})).toBeVisible({timeout:30000})
 await page.locator('input[aria-label="Mehrere PDFs importieren"]').setInputFiles(files)
 await expect(page.locator('.cine-crumbs')).toContainText('LOCAL-', {timeout:30000})
 await expect(page.getByRole('heading',{name:/Something doesn't add up/})).toBeVisible()
 await page.getByRole('tab',{name:/Die Handlung/}).click()
 await page.getByText('Dokumentarten prüfen & korrigieren').click()
 await page.getByRole('combobox',{name:'Dokumentart für CASE-123__Rechnung.pdf'}).selectOption('unknown')
 await expect(page.locator('.cine-issue-label')).toContainText('AKTE UNVOLLSTÄNDIG')
 await expect(page.getByRole('button',{name:/Zur Fachprüfung/})).toHaveCount(0)
 await page.getByRole('combobox',{name:'Dokumentart für CASE-123__Rechnung.pdf'}).selectOption('invoice')
 await expect(page.locator('.cine-issue-label')).toContainText('POTENZIELLER WIDERSPRUCH')
})
