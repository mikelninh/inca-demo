test('v8 mobile puts actual finding before small PDF preview and opens full-screen original',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/inca-demo/')
 await expect(page.getByRole('heading',{name:/Something doesn't add up/})).toBeVisible({timeout:30000})
 const positions=await page.evaluate(()=>{
  const story=document.querySelector('.cine-stage-right')!.getBoundingClientRect()
  const original=document.querySelector('.cine-stage-left')!.getBoundingClientRect()
  const preview=document.querySelector('.cine-document-viewport')!.getBoundingClientRect()
  return {storyY:story.y,sourceY:original.y,previewH:preview.height}
 })
 expect(positions.storyY).toBeLessThan(positions.sourceY)
 expect(positions.previewH).toBeLessThanOrEqual(180)
 await page.screenshot({path:'test-results/v8/05-mobile-story.png',animations:'disabled',fullPage:true})
 await page.getByRole('button',{name:/Originaldokument als Vollbild/}).click()
 const dialog=page.getByRole('dialog',{name:'Originaldokument Vollbild'})
 await expect(dialog).toBeVisible()
 await expect(dialog.locator('.cine-paper canvas')).toBeVisible()
 await dialog.getByRole('button',{name:'Vollbild PDF vergrößern'}).click()
 await expect(dialog.locator('.cine-page-controls output').last()).toContainText('125%')
 await dialog.getByRole('button',{name:/Schließen/}).click()
 await expect(dialog).toHaveCount(0)
 await page.getByRole('tab',{name:/Die Fundstelle/}).click()
 await page.getByRole('button',{name:/Fundstelle im Original-PDF sehen/}).click()
 await expect(dialog.locator('.cine-source-highlight').first()).toBeVisible({timeout:15000})
 await page.screenshot({path:'test-results/v8/06-mobile-original.png',animations:'disabled'})
 await page.keyboard.press('Escape')
 await expect(dialog).toHaveCount(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
})

