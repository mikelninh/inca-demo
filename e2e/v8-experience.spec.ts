import {test,expect} from '@playwright/test'
import {mkdir} from 'node:fs/promises'

test('v8 story reveals an actual PDF proof, in three acts, without covering the next action',async({page})=>{
 await page.setViewportSize({width:1440,height:900})
 await page.goto('/inca-demo/')
 await expect(page.getByRole('heading',{name:/Something doesn't add up/})).toBeVisible({timeout:30000})
 await expect(page.locator('.cine-view-switch')).toBeVisible()
 await expect(page.getByRole('button',{name:'Story',exact:true})).toHaveAttribute('aria-pressed','true')
 await expect(page.locator('.cine-main-stage')).toHaveClass(/cine-main-stage/)
 await mkdir('test-results/v8',{recursive:true})
 await page.screenshot({path:'test-results/v8/01-story.png',animations:'disabled'})
 await page.getByRole('button',{name:/Beleg entdecken/}).click()
 await expect(page.locator('.cine-evidence-reveal')).toBeVisible()
 await expect(page.locator('.cine-source-highlight').first()).toBeVisible({timeout:15000})
 await expect(page.locator('.cine-quote')).toContainText('WORTGLEICH IM ORIGINAL')
 // The next-step CTA must be topmost and actually clickable; old v7 could be overlaid by the quote.
 const cta=page.getByRole('button',{name:/Nächste Handlung/})
 const rect=await cta.boundingBox()
 expect(rect).not.toBeNull()
 await page.screenshot({path:'test-results/v8/02-reveal.png',animations:'disabled'})
 await cta.click({timeout:6000})
 await expect(page.getByRole('heading',{name:'The decision stays human.'})).toBeVisible()
 await page.screenshot({path:'test-results/v8/03-decision.png',animations:'disabled'})
})

