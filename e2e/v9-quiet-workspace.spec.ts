 await expect(page.locator('.quiet-docbar')).toContainText('Werkstattrechnung')
 await expect(page.locator('.quiet-highlight').first()).toBeVisible({timeout:15000})
 await expect(page.locator('.quiet-findings')).toContainText('Mögliche Abweichung')
 await expect(page.locator('.quiet-quote')).toContainText('WORTGLEICH IM ORIGINAL')
 await expect(page.getByRole('button',{name:'An Spezialist:in übergeben'})).toBeVisible()
 await mkdir('test-results/v9',{recursive:true})
 await expect(page.locator('.quiet-pdf-loading')).toHaveCount(0,{timeout:15000})
 await page.screenshot({path:'test-results/v9/01-desktop-quiet.png',animations:'disabled'})
 const citation=page.locator('.quiet-citation').filter({hasText:'Deckungsgrenze'}).last()
